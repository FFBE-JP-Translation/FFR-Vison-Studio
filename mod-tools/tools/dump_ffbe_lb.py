"""Dump a form's LB mechanics and sound references under abilities/<name>."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path

import ffbe_audio
import ffbe_lb
from ffbe_effects.acb_cues import utf


def inspect_awb(data):
    """Read the embedded stream headers; CPK encryption and HCA ciphers differ."""
    if data[:4] != b"AFS2":
        raise ValueError("Expected AFS2 embedded wave bank")
    offset_size, id_size = data[5:7]
    count = int.from_bytes(data[8:12], "little")
    alignment = int.from_bytes(data[12:14], "little")
    if offset_size not in (2, 4, 8) or id_size not in (2, 4) or not alignment:
        raise ValueError("Unsupported AFS2 layout")
    offsets = 16 + count * id_size
    streams = {}
    for i in range(count):
        wave_id = int.from_bytes(data[16+i*id_size:16+(i+1)*id_size], "little")
        start = int.from_bytes(data[offsets+i*offset_size:offsets+(i+1)*offset_size], "little")
        end = int.from_bytes(data[offsets+(i+1)*offset_size:offsets+(i+2)*offset_size], "little")
        start = (start + alignment - 1) // alignment * alignment
        if not 0 <= start < end <= len(data):
            raise ValueError("AFS2 stream outside bank")
        raw = data[start:end]
        header_size = int.from_bytes(raw[6:8], "big")
        header = bytes(b & 0x7f for b in raw[:header_size])
        cipher = header.find(b"ciph")
        streams[wave_id] = {"waveId": wave_id, "offset": start, "size": end-start,
                            "codec": "HCA" if header[:4] == b"HCA\0" else "unknown",
                            "cipherType": int.from_bytes(raw[cipher+4:cipher+6], "big") if cipher >= 0 else None}
    return streams


def dump(form, directory, bank_path=None):
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    source = ffbe_lb.resolve({"ffbe": {"id": str(form)}}, {})
    if source is None:
        raise ValueError(f"No LB source for form {form}")
    variants = [ffbe_lb.resolve({"ffbe": {"id": str(form)}}, {"ffbe_lb_id": lid}) for lid in source["availableLbIds"]]
    source = variants[0]
    profiles = [ffbe_lb.profile(s) for s in variants]
    bank = None
    if bank_path and Path(bank_path).is_file():
        path = Path(bank_path).resolve()
        data = path.read_bytes()
        header = utf(data)[1][0]
        streams = inspect_awb(header["AwbFile"])
        info = ffbe_audio.bank_info(str(path), path.stat().st_mtime_ns)
        waves = utf(header["WaveformTable"])[1]
        bank = {"path": str(path), "sha256": hashlib.sha256(data).hexdigest(), "container": "loose ACB with embedded AFS2",
                "waveCount": len(streams), "cipherTypes": dict(Counter(s["cipherType"] for s in streams.values())),
                "playback": "The original routed bank distorted audio in FFR. Native one-shot banks are under local test.",
                "cpkExtractor": "T:/Projects/FFBE Patch/cpk_2/DataExtractor.exe"}
        for s in variants:
            for sound in s["sounds"]:
                cue = info["cues"].get(sound["cueId"])
                if cue:
                    sound.update({"cueName": cue["name"], "durationMs": cue["durationMs"],
                                  "referenceType": cue["referenceType"], "referenceIndex": cue["referenceIndex"]})
                    sound.pop("firstWave", None)
                    sound["waveforms"] = [streams[waves[wi]["MemoryAwbId"]] for wi in cue["waveformIndices"]]
                    preview = directory / "sounds" / (cue["name"] + ".wav")
                    if preview.is_file():
                        sound["preview"] = preview.relative_to(directory).as_posix()
    result = {"form": str(form), "variants": variants, "profiles": profiles, "audioBank": bank}
    for region in ("jp", "gl"):
        forms, lbs, path = ffbe_lb.datamine(region)
        if str(form) in forms:
            maximum = str(forms[str(form)].get("lb_max_level", 1))
            result["datamineCrossCheck"] = {"path": path, "maxLevel": int(maximum),
                "variants": {s["lbId"]: {"level1": (lbs.get(s["lbId"], {}).get("levels") or {}).get("1"),
                                          "maxLevel": (lbs.get(s["lbId"], {}).get("levels") or {}).get(maximum)} for s in variants}}
            break
    (directory / "source.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (directory / "resonance.json").write_text(json.dumps(variants[0], ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    p = profiles[0]
    lines = [f"# LB source data: form {form}", "", "Generated by `tools/dump_ffbe_lb.py`. Full raw rows, all variants, effect-group flags, sound cues and cross-checks are in `source.json`.", "",
             "## Mechanics", "", "| LB | Elements | Damage target | Hits | Source multiplier (level 1) | FFR total power |", "|---|---|---|---|---|---|"]
    for v in profiles:
        lines.append(f"| {v['lbId']} | {', '.join(v['elements']) or 'None'} | {v.get('target', 'Unresolved')} | {v['hits']} | {v.get('sourceMultiplier')}x | {v.get('totalPower', 'Unresolved')} |")
    lines += ["", "Only damage-component hits become FFR damage reactions. The other FFBE effects remain recorded separately; their buffs/debuffs are not imported by this resonance adapter.",
              "Cloud reference: skill 440110, base power 36, with its level-scaling effect 12966 and critical bonus 13301. Hit weights sum to one; total base power stays 36, rather than multiplying by the new hit count. Actual damage also depends on combatant stats, defence, resistance and criticals.", "",
              "## Movement", "", f"- LB move type: `{source['moveType']}`. Unit move speed: `{source['movement']['speed']}`; LB wait: `{source['wait']}`.",
              f"- Raw UnitMst MoveOffset: `{source['movement']['rawOffset']}`.",
              f"- Normal attack offset: `{source['movement']['normalOffset']}`; LB offset: `{source['movement']['lbOffset']}`.",
              f"- Source offset maps to FFR `{source['movement']['ffrTargetOffset']}`. The current adapter adds 200 on Y (screen right), with native combatant spacing enabled.",
              "- FFBE horizontal maps to FFR +Y (party side); FFBE ground depth maps to -X. No sprite bounds or animation extent is used.",
              "- `BattleCharacter::getMoveOffset(int)` at `0x13c35b4` selects UnitMst+0x1c8 for action type 6; `UnitMst::getMoveOffsetLb()` at `0x1c43a80` returns that field. The normal field is +0x1c0. Evidence binary: `T:/Projects/FFBE Patch/tools/workspace/apk-decoded/lib/arm64-v8a/libgame.so`.",
              "- The 12 native FFR frames used for approach/return are adapter timing, not the FFBE MoveSpeed value. Mapping travel speed across engines remains unverified.", "",
              "## Hit frames", "", "Frames are relative to LB motion start at 60 fps. The FFR sequence starts LB1 at 0.5 seconds.", "",
              "| Hit | FFBE frame | Seconds into LB | Damage share | FFR base power share |", "|---|---|---|---|---|"]
    for i, (frame, weight) in enumerate(zip(source.get("hitFrames", []), source.get("hitPercents", [])), 1):
        lines.append(f"| {i} | {frame} | {frame/60:.4f} | {weight}% | {weight * p.get('totalPower', 0)/100:.4f} |")
    lines += ["", "## Sounds", "", "The source cues and existing decoded WAV previews are retained here. Local tests use rebuilt one-shot banks; the original routed bank produced distorted playback. A preview may represent one of a cue's alternative recordings.", "",
              "| FFBE frame | Seconds into LB | Cue ID | Cue name | Group | Preview |", "|---|---|---|---|---|---|"]
    for sound in source["sounds"]:
        preview = f"[{sound['cueName']}]({sound['preview']})" if sound.get("preview") else "—"
        lines.append(f"| {sound['frame']} | {sound['frame']/60:.4f} | {sound['cueId']} | {sound.get('cueName', 'unresolved')} | {sound['groupId']} | {preview} |")
    if bank:
        lines += ["", f"Bank: `{bank['path']}`. SHA-256: `{bank['sha256']}`.",
                  f"Embedded HCA cipher-type counts: `{bank['cipherTypes']}`. Type 0 is unencrypted; the CPK encryption hypothesis does not explain these stream headers. The cause of distorted playback is still unresolved.",
                  f"Located extractor: `{bank['cpkExtractor']}`. It handles FFBE CPK file extraction/decryption; this sound source is already a loose ACB."]
    (directory / "LB_DATA.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("form")
    parser.add_argument("directory")
    parser.add_argument("--audio-bank", default="S:/FFBE JP Data Export/public/SE.acb")
    args = parser.parse_args()
    dump(args.form, args.directory, args.audio_bank)
    print(f"LB source written to {args.directory}")
