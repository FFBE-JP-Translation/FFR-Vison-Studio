def category(name):
    if name in ('None', 'DamageAndRecovery') or any(s in name for s in ('Dmg', 'Damage', 'Crit', 'Break', 'SkillBase', 'BaseSkill')):
        return 'Damage & stagger'
    if any(s in name for s in ('Parameter', 'Recovery', 'Recover', 'LimitBurst', 'LB', 'MP', 'Cost', 'Heal')):
        return 'Resources & parameters'
    if any(s in name for s in ('Element', 'Status', 'Resist', 'Reflect', 'Deffence', 'Defence', 'Avoid', 'Cover', 'Reprieve', 'Decoy', 'Hate', 'Camouflage')):
        return 'Statuses & protection'
    if any(s in name for s in ('Summon', 'Form', 'Member', 'DeathAnim', 'Seal', 'Demon')):
        return 'Actors & special states'
    if any(s in name for s in ('Experience', 'Money', 'APUp', 'Steal', 'Drop', 'Encount', 'Preemt', 'Escape', 'Analyze')):
        return 'Rewards & exploration'
    return 'Actions & special mechanics'
