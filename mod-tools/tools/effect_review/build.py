def full_coverage(effects):
    """Count every actual conversion record, including every LB level.

    Inventory examples are only display examples. This pass never samples.
    Unknown or malformed components remain counted and listed as anomalies.
    """
    counts, kinds, seen = Counter(), Counter(), Counter()
    variants = defaultdict(Counter)
    anomalies, empty, total = [], 0, 0
    original_counts = Counter()
    effect_records = Counter()
    for record in iter_complete_sources():
        counts[record.source] += 1
        kinds[record.kind] += 1
        total += 1
        raws = record.data.get('effects_raw') or []
        if not raws:
            empty += 1
        for issue in record.issues:
            anomalies.append({'record': record.key, 'issue': issue})
        record_keys = set()
        for raw in raws:
            size, pos = (3, 1) if record.namespace == 'field' else (4, 2)
            if not isinstance(raw, list) or len(raw) != size or type(raw[pos]) is not int:
                anomalies.append({'record': record.key, 'issue': 'Malformed component', 'raw': raw})
                continue
            key = f'{record.namespace}:{raw[pos]}'
            seen[key] += 1
            record_keys.add(key)
            if not (record.source == 'JP_CLIENT' and record.level is not None):
                original_counts[key] += 1
            variants[key][json.dumps(raw[:pos], separators=(',', ':'))] += 1
        effect_records.update(record_keys)
        if total % 100000 == 0:
            print(f'Counted {total:,} complete source records', flush=True)
    known = {x['key'] for x in effects}
    if set(seen) - known:
        raise ValueError(f'Inventory omitted observed keys: {sorted(set(seen)-known)}')
    for effect in effects:
        if original_counts[effect['key']] != effect['occurrences']:
            raise ValueError(f"Effect count mismatch for {effect['key']}: {original_counts[effect['key']]} vs {effect['occurrences']}")
        effect['previousInventoryOccurrences'] = effect['occurrences']
        effect['occurrences'] = seen[effect['key']]
        effect['recordCount'] = effect_records[effect['key']]
        added = seen[effect['key']] - original_counts[effect['key']]
        if added:
            effect['sourceCounts']['JP_CLIENT_LB_LEVELS'] = added
        effect['targetVariants'] = [{'raw': json.loads(k), 'count': v} for k, v in variants[effect['key']].most_common()]
    # Leaders reference the same skills, rather than declaring a fourth opcode namespace.
    leader_counts, leader_missing = {}, []
    for region in ('gl', 'jp'):
        base = Path(f'T:/Projects/ffbe/ffbe-wiki-tools/datamine/data/{region}')
        leaders, skills = read(base/'leader_skills.json'), read(base/'skills.json')
        leader_counts[region.upper()] = len(leaders)
        for key, entry in leaders.items():
            if str(entry['skill_id']) not in skills:
                leader_missing.append({'region': region, 'leader': key, 'skill': entry['skill_id']})
    return {'totalRecords': total, 'bySource': dict(counts), 'byKind': dict(kinds),
            'components': sum(seen.values()), 'recordsWithoutComponents': empty,
            'listedEffects': len(effects), 'observedEffects': len(seen),
            'anomalies': anomalies, 'leaderReferences': leader_counts, 'missingLeaderSkills': leader_missing,
            'allLbLevels': True, 'sampled': False}


def make_guide(ffr, catalog):
    names = {kind: {v['id']: v for v in catalog[kind]} for kind in ('skills', 'passives')}
    assert set(NOTES) == {v['type'] for v in ffr['effectTypes']}, 'Every FFR type needs a readup'
    guide = []
    for effect in ffr['effectTypes']:
        item = {**effect, 'summary': NOTES[effect['type']], 'category': category(effect['type'])}
        examples, ids = [], set()
        for row in effect['effectRows']:
            for use in row['usedBy']:
                key = (use['kind'], use['id'])
                if key not in ids:
                    ids.add(key)
                    examples.append({**use, 'effectId': row['ID'], 'description': names[use['kind']].get(use['id'], {}).get('desc', '')})
        for direct in effect['directSkillRows']:
            entry = names['skills'].get(direct['id'], {})
            examples.append({'kind': 'skills', 'id': direct['id'], 'row': direct['row'],
                             'name': entry.get('name', direct['row']), 'description': entry.get('desc', ''),
                             'direct': True})
        item['examples'] = examples
        item['support'] = 'Native skill usage' if examples else 'Effect rows only' if effect['effectRows'] else 'Declared only'
        guide.append(item)
    return guide


def decisions(effects, proposals):
    result = {}
    overrides = {
        'active:1': ('preset:physical_damage', 'Physical HP damage. Preserve compatible damage independently from other components.'),
        'active:15': ('preset:magic_damage', 'Magic HP damage. Preserve compatible damage independently from other components.'),
        'active:40': ('preset:magic_damage', 'Earlier proposal: replace hybrid damage with normalized magic damage. Awaiting this review.'),
        'active:130': ('policy:normal_cooldown', POLICIES['cooldowns']),
        'active:30': ('preset:mp_recovery', POLICIES['mpLbRegeneration']),
        'active:57': ('preset:mp_recovery', 'MP recovery once; remove singing lock and periodic ticks. Amount remains a reviewed adaptation.'),
        'passive:32': ('preset:mp_recovery', 'One MP recovery instead of regeneration. Proposed trigger: once at battle start; review before conversion.'),
        'passive:110': ('preset:mp_recovery', 'One full MP recovery on BOOST activation if that trigger can be bound; otherwise report this component as incompatible. Do not refill every turn.'),
        'active:125': ('preset:resonance_recovery', POLICIES['lbRecovery']),
        'active:1003': ('preset:resonance_recovery', POLICIES['lbRecovery']),
        'active:31': ('preset:resonance_recovery', 'Entrust becomes resonance recovery for its main-cast recipient. Preserve or explicitly replace the donor gauge cost; the amount/cost decision remains in review.'),
        'passive:33': ('preset:resonance_recovery', 'One main-cast resonance recovery instead of every-turn LB fill. Proposed trigger: once at battle start; amount awaits review.'),
        'passive:109': ('preset:resonance_recovery', 'One main-cast resonance recovery on BOOST activation if that trigger can be bound; otherwise incompatible. No repeated refill.'),
        'active:131': ('ffr:DamageAndRecovery', 'This is a damage song, despite the old formatter label “Song MP heal”. Preserve compatible damage; do not turn enemy damage into MP recovery. Singing/tick scheduling needs its own decision.'),
        'field:4': ('ffr:ParameterVariation', 'Decode HP, MP, LB and esper subfields separately. MP/LB become one immediate recovery; LB targets the main cast. Keep compatible subfields and report unsupported ones. Field recipient and activation still need binding.'),
        'active:170': ('skip', 'Cooldown reduction has no useful effect when cooldown moves are ordinary moves. Drop this component; preserve any compatible siblings.'),
        'passive:113': ('skip', 'BOOST cooldown reduction has no useful effect when cooldown moves are ordinary moves. Drop this component; preserve compatible siblings.'),
    }
    for effect in effects:
        key = effect['key']
        proposal = proposals.get(key, {})
        candidates = [f"ffr:{x['type']}" for x in proposal.get('nativeCandidates', [])]
        strategy = proposal.get('strategy', 'REVIEW')
        selection = candidates[0] if candidates else 'other'
        intent = proposal.get('proposal', 'No decoded mapping yet. Choose an FFR effect or add notes.')
        if strategy == 'NO_OP':
            selection = 'skip'
        elif strategy in ('REVIEW', 'DEFINITION_ONLY', 'PRESENTATION_REVIEW') or effect['evidence'] == 'unresolved':
            selection = 'other'
        if key in overrides:
            selection, intent = overrides[key]
        effect['proposal'] = proposal
        effect['suggestedIntent'] = intent
        result[key] = {'targets': [selection], 'notes': '', 'reviewed': False}
    return result


def main():
    effects, ffr = read(INVENTORY/'ffbe-effects.json'), read(INVENTORY/'ffr-effects.json')
    # Correct a demonstrably incorrect historical formatter title; retain evidence.
    for effect in effects:
        if effect['key'] == 'active:131':
            effect['originalLabel'] = effect['label']
            effect['label'] = 'Damage song (old formatter mislabeled as MP heal)'
            effect['labelCorrection'] = 'Client template and aligned Requiem of Ruin example both describe enemy damage.'
    coverage = full_coverage(effects)
    guide = make_guide(ffr, read(ROOT/'build/devui/ffr_catalog.json'))
    proposals = {v['key']: v for v in read(ROOT/'docs/build16/proposed-map.json')['effects']}
    choices = decisions(effects, proposals)
    options = [{'id': 'other', 'label': 'Other / write notes', 'group': 'Review choices', 'summary': 'Describe the intended behavior. This remains an implementation decision, not an automatic no-op.'},
               {'id': 'skip', 'label': 'Drop this component', 'group': 'Review choices', 'summary': 'Explicitly omit this component while retaining compatible parts of the ability.'},
               {'id': 'policy:normal_cooldown', 'label': 'Ordinary move (remove cooldown)', 'group': 'Review choices', 'summary': POLICIES['cooldowns']}]
    options.extend({'id': f'preset:{key}', 'label': label, 'group': 'Common FFR behaviors', 'type': native, 'summary': description}
                   for key, label, native, description in PRESETS)
    options.extend({'id': f"ffr:{e['type']}", 'label': e['type'], 'type': e['type'],
                    'group': 'FFR — declared only' if e['support'] == 'Declared only' else 'FFR — native rows / skills',
                    'summary': e['summary'], 'support': e['support']} for e in guide)
    sources = read(INVENTORY/'sources.json')
    for region in ('gl', 'jp'):
        path = Path(f'T:/Projects/ffbe/ffbe-wiki-tools/datamine/data/{region}/leader_skills.json')
        sources[str(path)] = {'bytes': path.stat().st_size, 'sha256': sha(path)}
    for path in [ROOT/'build/devui/live_jp/F_LIMITBURST_LV_MST.json', ROOT/'docs/build16/proposed-map.json', HERE/'build.py', HERE/'sources.py', HERE/'ffr_readup.py', ROOT/'tools/ability_converter/sources.py']:
        sources[str(path)] = {'bytes': path.stat().st_size, 'sha256': sha(path)}
    fingerprint = hashlib.sha256(json.dumps(sources, sort_keys=True).encode()).hexdigest()
    data = {'schemaVersion': 1, 'catalogId': fingerprint, 'builtAt': datetime.now(timezone.utc).isoformat(),
            'coverage': coverage, 'policies': POLICIES, 'effects': effects, 'ffr': guide, 'options': options,
            'defaults': choices, 'sources': sources, 'nativeCounts': ffr['counts'], 'statuses': ffr['statuses'],
            'enums': ffr['enums'], 'skillAxes': ffr['skillAxes']}
    OUT.mkdir(parents=True, exist_ok=True)
    write(OUT/'catalog.json', data)
    write(OUT/'coverage.json', coverage)
    write(OUT/'source-manifest.json', sources)
    write(OUT/'mapping-defaults.json', {'schemaVersion': 1, 'catalogId': fingerprint, 'stage': 'mapping',
                                     'revision': 0, 'decisions': choices, 'policies': POLICIES})
    write(OUT/'ffr-readup.json', guide)
    payload = json.dumps(data, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    template = (HERE/'review.html').read_text(encoding='utf-8')
    (OUT/'index.html').write_text(template.replace('/*__CATALOG__*/', payload), encoding='utf-8')
    fonts = OUT/'fonts'
    fonts.mkdir(exist_ok=True)
    for name in ('Barlow-Regular.ttf', 'Barlow-SemiBold.ttf', 'BarlowCondensed-Bold.ttf', 'OFL.txt'):
        shutil.copyfile(ROOT/'app/ffr_vision_studio/assets/fonts'/name, fonts/name)
    lines = ['# FFR effect readup', '', 'All 194 declared types. Orientation notes describe purpose; native game descriptions, rows and timing are the evidence. Native presence is separate from a working FFBE conversion. Enum-only operations remain selectable review proposals.', '']
    for item in guide:
        lines.extend([f"## {item['type']} ({item['code']})", '', item['summary'], '',
                      f"Evidence: {item['support']}; {len(item['effectRows'])} effect rows, {len(item['directSkillRows'])} direct skill rows.", ''])
        for example in item['examples'][:4]:
            lines.append(f"- {example['name'] or example['row']} ({example['id']}): {example['description']}")
        lines.append('')
    (OUT/'ffr-readup.md').write_text('\n'.join(lines), encoding='utf-8')
    def cell(value):
        return str(value).replace('|', '\\|').replace('\n', ' ')
    lines = ['# FFBE → FFR parity table', '', 'Draft decisions; edit in index.html. All listed effects are included, including definition-only codes. Alternative native candidates are suggestions, not extra unconditional effects.', '',
             '| FFBE key | Meaning | Occurrences | Default selection | Treatment |', '|---|---|---:|---|---|']
    for e in effects:
        lines.append(f"| {e['key']} | {cell(e['label'])} | {e['occurrences']} | {cell(', '.join(choices[e['key']]['targets']))} | {cell(e['suggestedIntent'])} |")
    (OUT/'parity-table.md').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    print(json.dumps({k: v for k, v in coverage.items() if k != 'anomalies'}, indent=2), flush=True)


if __name__ == '__main__':
    main()
