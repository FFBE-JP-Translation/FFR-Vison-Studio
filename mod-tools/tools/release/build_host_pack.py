r"""build_host_pack.py - the static files the native app downloads, laid out for the two (plus N) Hostinger sites.

Build 13 adds ffbe/units/<form>.ffr and ffbe/idle/<form>.webp, routed through
unitBundles in the index to separate units<n> sites. The old forms/sprite URLs
remain available. Startup uses compact catalog/common ZIPs and a content-hashed
icon ZIP; individual shared HCA recordings live in ffbe/audio/. Build 14 adds
one content-addressed idle ZIP on --idle-host (default idle.luminest.io).
--app-source selects an isolated Flutter source tree when the regular exe is open.
--unit-assets DIR reuses a tree generated by unit_assets.py; --unit-host accepts
a https://units{n}.example/ pattern. Every new unit shard stays below --shard-mb.

    manifest.json                       version, and for each pack: url, sha256, size; sprites: count + shard hosts
    engine/engine-<version>.zip         the packaged engine: everything in the release folder except data/, mods/ and build
                                        outputs (the exe renamed "FFR Vision Studio Engine.exe"); hosted on the engine site
    data/base-<version>.zip             the shipped game-derived data (data/*.json, usmap, enums, icons, listing) -> engine data/
    ffbe/tables-<version>.zip           Brave Exvius tables + English names (data/ffbe minus sprites) -> engine data/ffbe/
    ffbe/index.json                     the unit index; each unit carries `packs` (forms with a sprite zip) and `hasSprites`;
                                        `forms[form]` = {url (absolute, on a sprite shard), size, sha256}
    ffbe/icons/<form>.png               every form's 56x38 face icon (kept for app builds 5 and 6, which fetch them one by one)
    ffbe/icons-<version>.zip            the same icons as one pack (build 7+ downloads it once; the pickers read it from disk)
    ffbe/sprites/<form>.zip             one zip per unit form (the form's files at the zip root), spread over sprite shards
    app/FFR-Vision-Studio-<version>.zip the Flutter app (folder "FFR Vision Studio <version>/", exe "FFR Vision Studio.exe")
    index.html, img/                    the download page (tools/release/site)

Hostinger's static deploy replaces a site's whole tree. The downloads are split across sites:
    deploy/engine-site-<v>.zip   -> ffr.luminest.io           (the engine, 76 MB)
    deploy/ffbe-site-<v>.zip     -> ffbe.luminest.io          (manifest, page, app, data, tables, index, icons; ~40 MB)
    deploy/sprites-<n>-<v>.zip   -> sprites<n>.luminest.io    (sprite zips, <= --shard-mb each; the index points at them)
Deploy the engine and sprite shards first, the ffbe site last (its manifest and index point at the others).
A pack whose content did not change since an earlier build keeps that build's zip and tag (`packs.<name>.version`): the app
skips what it already has, and the engine site only needs a deploy when the engine changed (the builder says so).

usage: python tools/release/build_host_pack.py <version> --build <n> [--build-app] [--min-app <tag>] [--sprites all|pack] [--shard-mb 70] [--shard-host https://sprites{n}.luminest.io/]
    <version> is the product version (1.0.0 while the first release is being worked on); --build counts the builds of it. Files,
    the manifest and the app compare the tag "<version>.<build>". --build-app runs `flutter build windows` with that version stamped
    into the exe (--build-name / --build-number / --dart-define APP_VERSION, APP_BUILD). --min-app is the oldest app tag that can
    drive this engine (default: this tag); an older app keeps its installed packs and asks for the new download.
                                                  [--shard-hosts a,b,c] [--engine-host https://ffr.luminest.io/] [--release DIR] [--ffbe-pack DIR] [--app DIR] [--out DIR]
"""
import hashlib, json, os, shutil, sys, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools", "devui"))


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""): h.update(chunk)
    return h.hexdigest()


def newest_mtime(src, skip=None):
    t = 0
    for dp, dns, fs in os.walk(src):
        rel_dir = os.path.relpath(dp, src)
        if skip and any((rel_dir == s or rel_dir.startswith(s + os.sep)) for s in skip): dns[:] = []; continue
        for f in fs: t = max(t, os.path.getmtime(os.path.join(dp, f)))
    return t


def zip_dir(src, dst, skip=None, rename=None, prefix=""):
    """Zips `src` into `dst`. An existing zip that is newer than every source file is kept as it is, so a re-run of the pack
    builder does not change bytes (and checksums) that are already deployed."""
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if os.path.exists(dst) and os.path.getmtime(dst) >= newest_mtime(src, skip):
        return {"size": os.path.getsize(dst), "sha256": sha256(dst)}
    with zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as z:
        for dp, dns, fs in os.walk(src):
            rel_dir = os.path.relpath(dp, src)
            if skip and any((rel_dir == s or rel_dir.startswith(s + os.sep)) for s in skip): dns[:] = []; continue
            for f in fs:
                p = os.path.join(dp, f); rel = os.path.normpath(os.path.join(rel_dir, f)).replace("\\", "/")
                if rel.startswith("./"): rel = rel[2:]
                if rename and rel in rename: rel = rename[rel]
                z.write(p, prefix + rel)
    return {"size": os.path.getsize(dst), "sha256": sha256(dst)}


def stable_zip(out_sub, kind, ver, src, skip=None, rename=None):
    """The pack `<out_sub>/<kind>-<tag>.zip`: an earlier build's zip is kept (with its tag) when every source file is older than
    it, so a pack only changes when its content does. Returns (path, tag, {size, sha256})."""
    d = out_sub; os.makedirs(d, exist_ok=True)
    newest = newest_mtime(src, skip)
    olds = sorted((f for f in os.listdir(d) if f.startswith(kind + "-") and f.endswith(".zip")),
                  key=lambda f: [int(x) if x.isdigit() else 0 for x in f[len(kind) + 1:-4].split(".")], reverse=True)
    for f in olds:
        fp = os.path.join(d, f)
        if os.path.getmtime(fp) >= newest:
            return fp, f[len(kind) + 1:-4], {"size": os.path.getsize(fp), "sha256": sha256(fp)}
    fp = os.path.join(d, f"{kind}-{ver}.zip")
    if os.path.exists(fp): os.remove(fp)
    return fp, ver, zip_dir(src, fp, skip=skip, rename=rename)


def zip_files(files, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as z:
        for p in files:
            if os.path.isfile(p): z.write(p, os.path.basename(p))
    return {"size": os.path.getsize(dst), "sha256": sha256(dst)}


def arg(a, name, default):
    return a[a.index(name) + 1] if name in a else default


def main():
    a = sys.argv[1:]
    if not a: sys.exit(__doc__)
    display = a[0]
    build = arg(a, "--build", None)
    ver = f"{display}.{build}" if build else display          # the tag: file names, manifest.version, the app's version compare
    min_app = arg(a, "--min-app", ver)
    rel = arg(a, "--release", os.path.join(ROOT, "build", "release", "FFR Vision Studio"))
    pack = arg(a, "--ffbe-pack", os.path.join(ROOT, "build", "release", "ffbe_pack"))
    out = arg(a, "--out", os.path.join(ROOT, "build", "release", "host"))
    engine_host = arg(a, "--engine-host", "https://ffr.luminest.io/")
    shard_host = arg(a, "--shard-host", "https://sprites{n}.luminest.io/")
    shard_hosts = [h.strip() for h in arg(a, "--shard-hosts", "").split(",") if h.strip()]   # explicit list wins over the pattern
    def host_for(n): return shard_hosts[n - 1] if n - 1 < len(shard_hosts) else shard_host.format(n=n)
    shard_mb = float(arg(a, "--shard-mb", "70"))
    sprites_mode = arg(a, "--sprites", "all")
    app_root = os.path.abspath(arg(a, "--app-source", os.path.dirname(ROOT)))
    app_dir = arg(a, "--app", os.path.join(app_root, "build", "windows", "x64", "runner", "Release"))
    os.makedirs(out, exist_ok=True)

    man = {"version": ver, "displayVersion": display, "build": int(build) if build else None, "minApp": min_app, "packs": {}}

    # engine: the release folder without data/ (ships as its own packs) and without mods/ (the user's units)
    eng_skip = ["data", "extracted", "build", "config.json", "mods", "logs"]
    vfile = os.path.join(rel, "VERSION")   # the engine reports it in /api/status; written only when the engine itself changed
    eng_dir = os.path.join(out, "engine")
    olds = [f for f in os.listdir(eng_dir)] if os.path.isdir(eng_dir) else []
    engine_changed = not any(os.path.getmtime(os.path.join(eng_dir, f)) >= newest_mtime(rel, eng_skip + ["VERSION"]) for f in olds if f.startswith("engine-"))
    if engine_changed and (not os.path.exists(vfile) or open(vfile, encoding="utf-8").read().strip() != ver): open(vfile, "w", encoding="utf-8").write(ver)
    eng, eng_tag, info = stable_zip(eng_dir, "engine", ver, rel, skip=eng_skip, rename={"FFR Vision Studio.exe": "FFR Vision Studio Engine.exe"})
    man["packs"]["engine"] = {"url": f"{engine_host}engine/{os.path.basename(eng)}", "version": eng_tag, **info}
    print("engine", man["packs"]["engine"]["size"] // 1048576, "MB", f"(build {eng_tag}, unchanged: no engine deploy needed)" if eng_tag != ver else "(new: deploy the engine site)")
    base, base_tag, info = stable_zip(os.path.join(out, "data"), "base", ver, os.path.join(rel, "data"), skip=["ffbe"])
    man["packs"]["base"] = {"url": f"data/{os.path.basename(base)}", "version": base_tag, **info}
    # the live JP units (newer than the datamine) travel with the tables as a compact file the user's engine can read
    try:
        import ffbe_catalog as fc0
        live = fc0.live_units()
        if live:
            lp = os.path.join(pack, "live_units.json"); txt = json.dumps(live, ensure_ascii=False)
            if not os.path.exists(lp) or open(lp, encoding="utf-8").read() != txt: open(lp, "w", encoding="utf-8").write(txt)
            print("live units", len(live))
    except Exception as ex: print("live units skipped:", ex)
    # The compact catalog/common packs and per-unit records are built below.
    # Do not upload the full datamine and complete SE bank to every client.

    # the unit index
    idx_path = os.path.join(ROOT, "build", "devui", "ffbe_index.json")
    units = json.load(open(idx_path, encoding="utf-8")) if os.path.exists(idx_path) else []

    import ffbe_catalog as fc

    # sprites: one zip per form. "all" = every form any unit lists (the developer's roots), "pack" = only the data pack's folders
    sp_out = os.path.join(out, "ffbe", "sprites"); os.makedirs(sp_out, exist_ok=True)
    if sprites_mode == "all":
        wanted = sorted({str(f) for u in units for f in (u.get("spriteForms") or [])})
    else:
        sp_src = os.path.join(pack, "sprites")
        wanted = sorted(os.listdir(sp_src)) if os.path.isdir(sp_src) else []
    forms = {}; made = 0
    for i, form in enumerate(wanted):
        dst = os.path.join(sp_out, f"{form}.zip")
        if not os.path.exists(dst):
            try: files = fc.sprite_files(form)
            except Exception: files = []
            files = [p for p in files if os.path.isfile(p)]
            if not any(os.path.basename(p) == f"unit_anime_{form}.png" for p in files): continue
            zip_files(files, dst); made += 1
            if made % 200 == 0: print(f"  {made} sprite zips made ({i + 1}/{len(wanted)} forms)")
        forms[form] = {"size": os.path.getsize(dst), "sha256": sha256(dst)}
    print(f"sprites: {len(forms)} forms ({made} new), {sum(v['size'] for v in forms.values()) // 1048576} MB")

    # shards: forms already on a shard (previous index) stay there, so a re-run only changes the shard that gains new forms;
    # new forms fill the last shard, then open new shards, up to shard_mb each
    limit = int(shard_mb * 1048576)
    prev_index = os.path.join(out, "ffbe", "index.json")
    prev = {}
    if os.path.exists(prev_index):
        try: prev = {f: v.get("url") for f, v in json.load(open(prev_index, encoding="utf-8")).get("forms", {}).items() if v.get("url")}
        except Exception: prev = {}
    hosts = []   # shard hosts as used before, in their numeric order (sprites1, sprites2, ..., sprites8)
    for f, url in prev.items():
        h = url.rsplit("/", 1)[0] + "/"
        if h not in hosts: hosts.append(h)
    hosts.sort(key=lambda h: int("".join(ch for ch in h.split("//")[-1].split(".")[0] if ch.isdigit()) or 0))
    shards = [[] for _ in hosts] or [[]]; sizes = [0] * len(shards)
    for form in sorted(forms):
        url = prev.get(form)
        if url:
            n = hosts.index(url.rsplit("/", 1)[0] + "/"); shards[n].append(form); sizes[n] += forms[form]["size"]
    changed = set()
    for form in sorted(forms):
        if prev.get(form): continue
        s = forms[form]["size"]
        if sizes[-1] + s > limit and shards[-1]: shards.append([]); sizes.append(0)
        shards[-1].append(form); sizes[-1] += s; changed.add(len(shards))
    for n, group in enumerate(shards, 1):
        host = hosts[n - 1] if n - 1 < len(hosts) else host_for(n)
        for form in group: forms[form]["url"] = f"{host}{form}.zip"
    if changed: print(f"shards that gained forms (deploy these): {sorted(changed)}")
    else: print("no shard changed")
    man["packs"]["sprites"] = {"count": len(forms), "shards": [(hosts[n - 1] if n - 1 < len(hosts) else host_for(n)) for n in range(1, len(shards) + 1)], "shardMB": [round(s / 1048576, 1) for s in sizes]}
    print(f"shards: {len(shards)} x <= {shard_mb} MB:", [round(s / 1048576) for s in sizes])

    # icons: one per form (the list shows the unit's iconForm, the look picker one per look); the folder stays for app builds
    # 5 and 6, which fetch them one by one; build 7+ downloads the icons pack once and reads it from disk
    icon_out = os.path.join(out, "ffbe", "icons"); os.makedirs(icon_out, exist_ok=True); n_icons = 0
    icon_forms = sorted(set(forms) | {str(u["iconForm"]) for u in units if u.get("iconForm")})
    for form in icon_forms:
        dst = os.path.join(icon_out, f"{form}.png")
        if os.path.exists(dst): n_icons += 1; continue
        src = fc.icon_png(form)
        if src: shutil.copy2(src, dst); n_icons += 1
    for u in units:
        if u.get("iconForm") and not os.path.exists(os.path.join(icon_out, f"{u['iconForm']}.png")): u["iconForm"] = None
    import unit_assets
    icons = os.path.join(out, "ffbe", "icons-current.zip")
    info = unit_assets.archive(icons, {f: open(os.path.join(icon_out, f), "rb").read() for f in sorted(os.listdir(icon_out)) if f.endswith(".png")})
    icon_named = os.path.join(out, "ffbe", f"icons-{info['sha256'][:16]}.zip")
    os.replace(icons, icon_named)
    icons = icon_named
    # Content identity also detects new icons when rebuilding the same tag.
    man["packs"]["icons"] = {"url": f"ffbe/{os.path.basename(icons)}", "version": info["sha256"], "count": n_icons, **info}
    print("icons", n_icons, "->", os.path.basename(icons), man["packs"]["icons"]["size"] // 1048576, "MB")

    for u in units:
        u["packs"] = sorted(f for f in (u.get("spriteForms") or []) if str(f) in forms)
        u["hasSprites"] = bool(u["packs"])
    import unit_assets, ffbe_categories
    legacy_forms = forms
    prepared = arg(a, "--unit-assets", None)
    if prepared:
        prepared_index = json.load(open(os.path.join(prepared, "ffbe", "index.json"), encoding="utf-8"))
        if set(prepared_index["unitBundles"]) != set(forms):
            raise ValueError("Prepared unit assets do not match this catalog")
        units = prepared_index["units"]
        forms = prepared_index["unitBundles"]
        for form, info in forms.items():
            host = legacy_forms[form]["url"].rsplit("/", 1)[0]
            info["url"] = f"{host}{form}.ffr"
            if info.get("idle"): info["idle"]["url"] = f"{host}{form}.webp"
        for sub in ("units", "idle", "audio"):
            shutil.copytree(os.path.join(prepared, "ffbe", sub), os.path.join(out, "ffbe", sub), dirs_exist_ok=True)
        prepared_packs = json.load(open(os.path.join(prepared, "asset-packs.json"), encoding="utf-8"))
        for name, info in prepared_packs.items():
            shutil.copy2(os.path.join(prepared, info["url"]), os.path.join(out, info["url"]))
            man["packs"][name] = info
    else:
        forms, man["packs"]["common"], man["packs"]["tables"] = unit_assets.build(units, forms, out, ver)
    # Unit records can be reused across app builds. The idle pack has its own
    # content hash and host so previews need one request, only when they change.
    man["packs"]["idles"] = unit_assets.idle_pack(out, forms, arg(a, "--idle-host", "https://idle.luminest.io/"))
    unit_host = arg(a, "--unit-host", "https://units{n}.luminest.io/")
    unit_shards, unit_sizes = unit_assets.route_bundles(forms, int(shard_mb * 1048576), unit_host)
    man["packs"]["unitBundles"] = {"count": len(forms), "shards": [unit_host.format(n=n) for n in range(1, len(unit_shards)+1)],
                                    "shardMB": [round(size / 1048576, 1) for size in unit_sizes]}
    json.dump({"version": ver, "units": units, "forms": legacy_forms, "unitBundles": forms, "categories": ffbe_categories.labels(), "icons": "ffbe/icons/"}, open(os.path.join(out, "ffbe", "index.json"), "w", encoding="utf-8"), ensure_ascii=False)
    print(f"index: {sum(1 for u in units if u['hasSprites'])}/{len(units)} units with sprites")

    # the desktop app (what people download): the Flutter release folder, zipped with a top-level folder, exe renamed
    if "--build-app" in a:
        import subprocess
        cmd = ["flutter", "build", "windows", "--release", "--build-name", display, "--build-number", build or "0",
               f"--dart-define=APP_VERSION={display}", f"--dart-define=APP_BUILD={build or 0}"]
        print("$", " ".join(cmd))
        r = subprocess.run(cmd, cwd=app_root, shell=True)
        if r.returncode != 0: sys.exit("flutter build failed")
    if os.path.isdir(app_dir):
        app_zip = os.path.join(out, "app", f"FFR-Vision-Studio-{ver}.zip")
        man["packs"]["app"] = {"url": f"app/FFR-Vision-Studio-{ver}.zip", **zip_dir(app_dir, app_zip, prefix=f"FFR Vision Studio {ver}/",
                                                                                     rename={"ffr_vision_studio.exe": "FFR Vision Studio.exe"})}
        print("app", man["packs"]["app"]["size"] // 1048576, "MB")

    # the download page (text files get the version and the app url; images are copied)
    site = os.path.join(ROOT, "tools", "release", "site"); site_files = set()
    if os.path.isdir(site):
        for dp, _, fs in os.walk(site):
            for f in fs:
                src = os.path.join(dp, f); r = os.path.relpath(src, site); dst = os.path.join(out, r)
                os.makedirs(os.path.dirname(dst), exist_ok=True); site_files.add(r.split(os.sep)[0])
                if f.endswith((".html", ".css", ".js", ".svg", ".txt")):
                    txt = (open(src, encoding="utf-8").read().replace("{{VERSION}}", display).replace("{{BUILD}}", str(build or "")).replace("{{TAG}}", ver)
                           .replace("{{UNITS}}", f"{len(units):,}".replace(",", " ")).replace("{{LOOKS}}", f"{len(forms):,}".replace(",", " "))   # the page's counts follow the index
                           .replace("{{APP_URL}}", man["packs"].get("app", {}).get("url", "#")))
                    open(dst, "w", encoding="utf-8").write(txt)
                else:
                    shutil.copy2(src, dst)
    json.dump(man, open(os.path.join(out, "manifest.json"), "w", encoding="utf-8"), indent=1)
    used = {os.path.basename(v["url"]) for v in man["packs"].values() if isinstance(v, dict) and v.get("url")}
    for sub in ("engine", "data", "app", "ffbe"):
        d = os.path.join(out, sub)
        for f in os.listdir(d) if os.path.isdir(d) else []:
            if f.endswith(".zip") and f not in used and f.split("-")[0] in ("engine", "base", "tables", "catalog", "common", "icons", "FFR"): os.remove(os.path.join(d, f))

    # deploy archives: the deploy strips the single top-level folder ("root/") and replaces the site with what is under it
    dep = os.path.join(os.path.dirname(out), "deploy"); os.makedirs(dep, exist_ok=True)
    for f in os.listdir(dep):
        if f.endswith(".zip") and f"-{ver}.zip" not in f: os.remove(os.path.join(dep, f))

    def deploy_zip(name, entries):
        """entries: (source path, path inside the site)"""
        dst = os.path.join(dep, name)
        with zipfile.ZipFile(dst, "w", zipfile.ZIP_STORED) as z:
            for src, rel in entries: z.write(src, "root/" + rel)
        print(f"deploy archive {name}: {os.path.getsize(dst) // 1048576} MB")

    def tree(sub):
        for dp, _, fs in os.walk(os.path.join(out, sub)):
            for f in fs:
                p = os.path.join(dp, f); yield p, os.path.relpath(p, out).replace(os.sep, "/")

    ffbe_entries = [(os.path.join(out, "manifest.json"), "manifest.json")] + list(tree("data")) + list(tree("app"))
    ffbe_entries += [(p, r) for p, r in tree("ffbe") if not r.startswith(("ffbe/sprites/", "ffbe/units/", "ffbe/idle/"))]
    for s in sorted(site_files): ffbe_entries += list(tree(s)) if os.path.isdir(os.path.join(out, s)) else [(os.path.join(out, s), s)]
    deploy_zip(f"ffbe-site-{ver}.zip", ffbe_entries)
    idle_name = os.path.basename(man['packs']['idles']['url'])
    deploy_zip(f"idle-site-{ver}.zip", [(os.path.join(out, 'previews', idle_name), 'previews/' + idle_name)])
    if eng_tag == ver: deploy_zip(f"engine-site-{ver}.zip", list(tree("engine")))
    else: print(f"engine unchanged since build {eng_tag}: no engine-site archive (ffr.luminest.io already serves {os.path.basename(eng)})")
    for n, group in enumerate(shards, 1):
        entries = [(os.path.join(sp_out, f"{form}.zip"), f"{form}.zip") for form in group]
        deploy_zip(f"sprites-{n}-{ver}.zip", entries)
    for n, group in enumerate(unit_shards, 1):
        entries = [(os.path.join(out, "ffbe", "units", f"{form}.ffr"), f"{form}.ffr") for form in group]
        entries += [(os.path.join(out, "ffbe", "idle", f"{form}.webp"), f"{form}.webp") for form in group if forms[form].get("idle")]
        deploy_zip(f"units-{n}-{ver}.zip", entries)
    print(f"host pack at {out}; deploy archives in {dep}")


if __name__ == "__main__":
    main()
